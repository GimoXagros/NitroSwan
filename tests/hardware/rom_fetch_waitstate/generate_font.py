def encode_tile(rows: tuple[str, ...]) -> bytes:
    output = bytearray()
    for y in range(8):
        plane0 = 0
        if 0 < y < 8:
            row = rows[y - 1]
            for x, pixel in enumerate(row):
                if pixel == "1":
                    plane0 |= 1 << (6 - x)
        output.extend((plane0, 0))
    return bytes(output)


def main() -> None:
    data = bytearray()
    blank = GLYPHS[" "]
    for codepoint in range(128):
        data.extend(encode_tile(GLYPHS.get(chr(codepoint), blank)))
    destination = Path(__file__).with_name("font.bin")
    destination.write_bytes(data)
    print(f"generated {destination} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
